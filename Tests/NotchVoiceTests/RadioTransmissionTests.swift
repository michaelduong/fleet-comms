import AVFoundation
import Foundation
@testable import NotchVoice
import Testing

struct RadioTransmissionTests {
    // Intent: FLC-6's accepted off-by-default setting, Police dispatch, and independent persistent static level.
    @Test @MainActor func defaultsAndPersistence() throws {
        let name = "radio-settings-\(UUID().uuidString)"
        let defaults = try #require(UserDefaults(suiteName: name))
        defer { defaults.removePersistentDomain(forName: name) }
        let fresh = AppSettings(defaults: defaults)
        #expect(!fresh.radio.enabled)
        #expect(fresh.radio.style == .policeDispatch)
        #expect(fresh.radio.staticLevel == 25)
        fresh.radio.enabled = true
        fresh.radio.style = .atcTransmission
        fresh.radio.staticLevel = 0
        let restored = AppSettings(defaults: defaults)
        #expect(restored.radio.enabled)
        #expect(restored.radio.style == .atcTransmission)
        #expect(restored.radio.staticLevel == 0)
        let control = RadioControl()
        control.update(defaults: defaults)
        let enabled = control.enabled.load(ordering: .relaxed)
        #expect(enabled)
        #expect(control.level.load(ordering: .relaxed) == 0)
        control.update(defaults: defaults, bypass: true)
        let bypassed = control.enabled.load(ordering: .relaxed)
        #expect(!bypassed)
    }

    // Intent: FLC-6 forbids noise on an underrun, and turning the feature off must preserve clean speech.
    @Test func silenceDoesNotOpenTransmission() {
        let control = RadioControl()
        let kernel = RadioKernel(control: control)
        kernel.prepare(sampleRate: 24000, style: .policeDispatch)
        for _ in 0 ..< 24000 {
            #expect(kernel.process(
                0,
                sampleRate: 24000,
                enabled: true,
                level: 1,
                style: .policeDispatch,
                hasAudio: false
            ) == 0)
        }
    }

    // Intent: FLC-6 requires actual native output insertion, bypass, streaming continuity and headroom.
    // Opt-in fixture is a neutral phrase generated by the system voice, never a provider or microphone recording.
    @Test(.enabled(if: ProcessInfo.processInfo.environment["FLEET_COMMS_RADIO_PROOF_WAV"] != nil))
    func nativeOutputAndChunkContinuity() throws {
        let path = try #require(ProcessInfo.processInfo.environment["FLEET_COMMS_RADIO_PROOF_WAV"])
        let file = try AVAudioFile(forReading: URL(fileURLWithPath: path))
        let source = try #require(AVAudioPCMBuffer(
            pcmFormat: file.processingFormat,
            frameCapacity: AVAudioFrameCount(file.length)
        ))
        try file.read(into: source)
        let converter = try #require(Resampler(from: file.processingFormat, to: RealtimeAudio.format))
        let samples = converter.convert(source)
        #expect(samples.count > 24000)
        for style in RadioStyle.allCases {
            let control = RadioControl()
            let whole = RadioKernel(control: control)
            let chunked = RadioKernel(control: RadioControl())
            whole.prepare(sampleRate: 24000, style: style)
            var expected = [Float]()
            var actual = [Float]()
            for sample in samples {
                expected.append(whole.process(sample, sampleRate: 24000, enabled: true, level: 1, style: style))
            }
            for start in stride(from: 0, to: samples.count, by: 137) {
                chunked.prepare(sampleRate: 24000, style: style)
                for sample in samples[start ..< min(start + 137, samples.count)] {
                    actual.append(chunked.process(sample, sampleRate: 24000, enabled: true, level: 1, style: style))
                }
            }
            #expect(actual == expected)
            #expect(actual.allSatisfy { $0.isFinite && abs($0) < 1 })
            #expect(actual != samples)
        }
        checkToggle(samples)
        try checkNativeInsert(samples, enabled: false)
        try checkNativeInsert(samples, enabled: true)
    }

    private func checkToggle(_ samples: [Float]) {
        let kernel = RadioKernel(control: RadioControl())
        kernel.prepare(sampleRate: 24000, style: .policeDispatch)
        for sample in samples {
            _ = kernel.process(sample, sampleRate: 24000, enabled: true, level: 0, style: .policeDispatch)
        }
        let bypass = samples.enumerated().map { index, sample in
            let output = kernel.process(sample, sampleRate: 24000, enabled: false, level: 0, style: .policeDispatch)
            return index < 480 || output == sample
        }
        let clean = bypass.allSatisfy(\.self)
        #expect(clean)
    }

    private func checkRendered(
        _ signal: (actual: [Float], expected: [Float]), enabled: Bool, engine: AVAudioEngine,
        radio: RadioOutput, output: AVAudioPCMBuffer
    ) throws {
        let rendered = signal.actual
        let samples = signal.expected
        if enabled {
            #expect(rendered != samples)
            #expect(rendered.contains { abs($0) > 0.001 })
            #expect(rendered.allSatisfy { $0.isFinite && abs($0) < 1 })
            _ = radio.finish()
            try #require(try engine.renderOffline(1024, to: output) == .success)
            let tail = UnsafeBufferPointer(start: output.floatChannelData![0], count: 1024)
            #expect(tail.contains { abs($0) > 0.0001 })
            radio.cancel()
            try #require(try engine.renderOffline(1024, to: output) == .success)
            #expect(output.floatChannelData![0][1023] == 0)
        } else {
            #expect(rendered == samples)
        }
    }

    private func checkNativeInsert(_ samples: [Float], enabled: Bool) throws {
        let name = "radio-output-\(UUID().uuidString)"
        let defaults = try #require(UserDefaults(suiteName: name))
        defer { defaults.removePersistentDomain(forName: name) }
        defaults.set(enabled, forKey: "radioEnabled")
        let engine = AVAudioEngine()
        let player = AVAudioPlayerNode()
        engine.attach(player)
        let format = RealtimeAudio.format
        let radio = try RadioOutput(engine: engine, player: player, format: format, defaults: defaults)
        try engine.enableManualRenderingMode(.offline, format: format, maximumFrameCount: 1024)
        let input = try #require(AVAudioPCMBuffer(pcmFormat: format, frameCapacity: AVAudioFrameCount(samples.count)))
        input.frameLength = AVAudioFrameCount(samples.count)
        samples
            .withUnsafeBufferPointer { input.floatChannelData![0].update(from: $0.baseAddress!, count: samples.count) }
        player.scheduleBuffer(input)
        try engine.start()
        player.play()
        radio.begin()
        let output = try #require(AVAudioPCMBuffer(pcmFormat: format, frameCapacity: 1024))
        var rendered = [Float]()
        while rendered.count < samples.count {
            let count = AVAudioFrameCount(min(1024, samples.count - rendered.count))
            let status = try engine.renderOffline(count, to: output)
            try #require(status == .success)
            rendered.append(contentsOf: UnsafeBufferPointer(start: output.floatChannelData![0], count: Int(count)))
        }
        try checkRendered((rendered, samples), enabled: enabled, engine: engine, radio: radio, output: output)
        engine.stop()
    }
}
